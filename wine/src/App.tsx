function FormWindow({ children, onSubmit }: { children: React.ReactNode; onSubmit: (event: FormEvent) => void | Promise<void> }) {
  return (
    <div
      className="form-modal"
      role="dialog"
      aria-modal="true"
      onMouseDown={(event) => {
        if (event.target !== event.currentTarget) return;
        event.currentTarget.querySelector<HTMLButtonElement>('.modal-back-button')?.click();
      }}
    >
      <form className="form-panel" onSubmit={onSubmit} onMouseDown={(event) => event.stopPropagation()}>
        {children}
      </form>
    </div>
  );
}

