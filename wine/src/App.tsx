function Metric({
  icon: Icon,
  label,
  value,
  compact = false,
  helper = '',
  tone = 'var(--accent)',
}: {
  icon: typeof Home;
  label: string;
  value: string | number;
  compact?: boolean;
  helper?: string;
  tone?: string;
}) {
  const valueText = String(value);
  const moneyValue = valueText.includes('R$');
  return (
    <article className={`metric-card ${compact ? 'mini' : ''} ${moneyValue ? 'money-value' : ''}`} style={{ '--metric-tone': tone } as React.CSSProperties}>
      <i className="metric-icon" aria-hidden="true">
        <Icon size={20} />
      </i>
      <span>{label}</span>
      <strong>{value}</strong>
      {helper && <small>{helper}</small>}
    </article>
  );
}

