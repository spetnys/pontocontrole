function matchesPeriod(value: string | undefined, period: PeriodFilter, direction: 'created' | 'due') {
  if (period === 'all') return true;
  const date = dateFromValue(value);
  if (!date) return false;

  const today = startOfDay(new Date());
  const day = startOfDay(date);
  const weekStart = addDays(today, -((today.getDay() + 6) % 7));
  const weekEnd = endOfDay(addDays(weekStart, 6));
  let start = today;
  let end = endOfDay(today);

  if (period === 'week') {
    start = direction === 'created' ? weekStart : today;
    end = direction === 'created' ? endOfDay(today) : weekEnd;
  }

  if (period === 'month') {
    start = direction === 'created' ? new Date(today.getFullYear(), today.getMonth(), 1) : today;
    end = direction === 'created' ? endOfDay(today) : new Date(today.getFullYear(), today.getMonth() + 1, 0, 23, 59, 59, 999);
  }

  if (period === 'six_months') {
    start = direction === 'created' ? addMonths(today, -6) : today;
    end = direction === 'created' ? endOfDay(today) : endOfDay(addMonths(today, 6));
  }

  if (period === 'year') {
    start = direction === 'created' ? new Date(today.getFullYear(), 0, 1) : today;
    end = direction === 'created' ? endOfDay(today) : new Date(today.getFullYear(), 11, 31, 23, 59, 59, 999);
  }

  return day >= start && day <= end;
}

function matchesFinancePeriod(record: Pick<FinanceRecord, 'dueDate' | 'paidAt'>, period: FinancePeriodFilter) {
  if (period === 'all') return true;
  const dates = [record.dueDate, record.paidAt]
    .map((value) => dateFromValue(value))
    .filter((date): date is Date => Boolean(date));
  if (dates.length === 0) return false;

  const today = startOfDay(new Date());
  const start = new Date(today.getFullYear(), today.getMonth(), 1);
  let end = new Date(today.getFullYear(), today.getMonth() + 1, 0, 23, 59, 59, 999);

  if (period === 'quarter') {
    end = new Date(today.getFullYear(), today.getMonth() + 3, 0, 23, 59, 59, 999);
  }

  if (period === 'semester') {
    end = new Date(today.getFullYear(), today.getMonth() + 6, 0, 23, 59, 59, 999);
  }

  if (period === 'year') {
    end = new Date(today.getFullYear(), today.getMonth() + 12, 0, 23, 59, 59, 999);
  }

  return dates.some((date) => {
    const day = startOfDay(date);
    return day >= start && day <= end;
  });
}

