    function moveAgenda(direction: -1 | 1) {
      if (agendaViewMode === 'month') setAgendaCursor(addMonths(agendaDate, direction));
      if (agendaViewMode === 'week') setAgendaCursor(addDays(agendaDate, direction * 7));
      if (agendaViewMode === 'day') setAgendaCursor(addDays(agendaDate, direction));
    }

    function eventsForDay(day: Date) {
      return visibleAgendaEvents.filter((event) => dateRangeOverlaps(event.startDate, event.endDate, startOfDay(day), endOfDay(day)));
    }

    function agendaMessage(event: AgendaForm) {
      const client = event.clientId ? clientName(event.clientId) : '';
      const service = event.serviceId ? serviceName(event.serviceId) : '';
      const activity = data.activities.find((item) => item.id === event.activityId);
      const resources = event.resourceIds.map(resourceName).join(', ');
      return [
        'Olá, você tem um compromisso agendado no Ponto Controle.',
        '',
        `Título: ${event.title || 'Compromisso sem título'}`,
        client ? `Cliente: ${client}` : '',
        service ? `Serviço: ${service}` : '',
        activity ? `Atividade: ${activity.title}` : '',
        `Data e horário: ${agendaPeriodLabel(event)}`,
        event.recurrence && event.recurrence !== 'none' ? `Repetição: ${agendaRecurrenceLabel(event.recurrence)}` : '',
        event.location ? `Local: ${event.location}` : '',
        resources ? `Participantes/equipe: ${resources}` : '',
        event.description ? `Observações: ${event.description}` : '',
      ].filter((line) => line !== '').join('\n');
    }

    function agendaIcs(event: AgendaForm) {
      const startDate = event.startDate || dateKey(new Date());
      const endDate = event.endDate || startDate;
      const uid = `${event.id || `agenda-${Date.now()}`}@ponto-controle`;
      const endDay = dateFromValue(endDate) || dateFromValue(startDate) || new Date();
      const startLine = event.allDay
        ? `DTSTART;VALUE=DATE:${icsDate(startDate)}`
        : `DTSTART:${icsDateTime(startDate, event.startTime || '09:00')}`;
      const endLine = event.allDay
        ? `DTEND;VALUE=DATE:${icsDate(dateKey(addDays(endDay, 1)))}`
        : `DTEND:${icsDateTime(endDate, event.endTime || event.startTime || '10:00')}`;
      const recurrenceLine = event.recurrence === 'weekly'
        ? 'RRULE:FREQ=WEEKLY'
        : event.recurrence === 'biweekly'
          ? 'RRULE:FREQ=WEEKLY;INTERVAL=2'
          : event.recurrence === 'monthly'
            ? 'RRULE:FREQ=MONTHLY'
            : '';
      return [
        'BEGIN:VCALENDAR',
        'VERSION:2.0',
        'PRODID:-//Ponto Controle//Agenda//PT-BR',
        'CALSCALE:GREGORIAN',
        'METHOD:PUBLISH',
        'BEGIN:VEVENT',
        `UID:${icsText(uid)}`,
        `DTSTAMP:${icsStamp()}`,
        startLine,
        endLine,
        `SUMMARY:${icsText(event.title || 'Compromisso Ponto Controle')}`,
        `DESCRIPTION:${icsText(agendaMessage(event))}`,
        event.location ? `LOCATION:${icsText(event.location)}` : '',
        recurrenceLine,
        `STATUS:${event.status === 'cancelled' ? 'CANCELLED' : 'CONFIRMED'}`,
        'END:VEVENT',
        'END:VCALENDAR',
      ].filter(Boolean).join('\r\n');
    }

    async function copyAgendaMessage(event: AgendaForm) {
      const message = agendaMessage(event);
      try {
        if (navigator.clipboard?.writeText) {
          await navigator.clipboard.writeText(message);
        } else {
          const textarea = document.createElement('textarea');
          textarea.value = message;
          textarea.style.position = 'fixed';
          textarea.style.opacity = '0';
          document.body.appendChild(textarea);
          textarea.focus();
          textarea.select();
          document.execCommand('copy');
          document.body.removeChild(textarea);
        }
        setNotice('Mensagem do convite copiada.');
      } catch {
        setNotice('Não foi possível copiar a mensagem.');
      }
    }

    function downloadAgendaInvite(event: AgendaForm) {
      const blob = new Blob([agendaIcs(event)], { type: 'text/calendar;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = agendaInviteFileName(event);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      window.setTimeout(() => URL.revokeObjectURL(url), 500);
      setNotice('Convite da agenda gerado.');
    }

