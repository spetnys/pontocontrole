  function serviceContractDraft(clientId: string, serviceId: string): ClientServiceContractDraft {
    const service = data.services.find((item) => item.id === serviceId);
    const existing = clientId
      ? clientContracts(clientId).find((contract) => contract.serviceId === serviceId && contract.status !== 'cancelled' && contract.status !== 'finished')
        || clientContracts(clientId).find((contract) => contract.serviceId === serviceId)
      : null;
    return {
      specificValue: existing?.specificValue ?? service?.baseValue ?? 0,
      quantity: serviceQuantity(existing?.quantity),
      periodicity: existing?.periodicity ?? service?.suggestedPeriodicity ?? 'monthly',
      dueDay: existing?.dueDay ?? 10,
      status: existing?.status === 'cancelled' ? 'active' : existing?.status ?? 'active',
      startDate: existing?.startDate ?? '',
      endDate: existing?.endDate ?? '',
    };
  }

  const resourceAllocatedServiceIds = useCallback((resourceId: string) => {
    const serviceIds = new Set<string>();
    (data?.services || []).forEach((service) => {
      if (service.resourceIds.includes(resourceId)) serviceIds.add(service.id);
    });
    (data?.clientServices || []).forEach((contract) => {
      if (contract.resourceIds.includes(resourceId) || contract.ownerResourceId === resourceId) serviceIds.add(contract.serviceId);
    });
    (data?.activities || []).forEach((activity) => {
      if (activity.resourceIds.includes(resourceId) && activity.serviceId) serviceIds.add(activity.serviceId);
    });
    return serviceIds;
  }, [data?.activities, data?.clientServices, data?.services]);

