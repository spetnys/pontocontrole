  function MultiUserPicker({
    value,
    onChange,
    clientId,
    masterCompanyId,
  }: {
    value: string[];
    onChange: (value: string[]) => void;
    clientId: string;
    masterCompanyId: string;
  }) {
    const users = clientPortalUsers().filter((user) => {
      if (masterCompanyId && user.masterCompanyId !== masterCompanyId) return false;
      const clientIds = user.permissions.allClients ? [] : user.permissions.clientIds || [];
      return clientIds.length === 0 || (clientId ? clientIds.includes(clientId) : value.includes(user.id));
    });
    if (users.length === 0) {
      return <p className="form-hint">Nenhum usuário de cliente livre para esta empresa master. Crie ou aprove o cadastro em Usuários.</p>;
    }

    return (
      <select
        className="multi-select-list"
        multiple
        size={Math.min(6, Math.max(3, users.length))}
        value={value.filter((userId) => users.some((user) => user.id === userId))}
        onChange={(event) => onChange(Array.from(event.currentTarget.selectedOptions).map((option) => option.value))}
      >
        {users.map((user) => (
          <option key={user.id} value={user.id}>
            {user.name} · {user.email}
          </option>
        ))}
      </select>
    );
  }

  function renderClientServicesField({
    clientId,
    masterCompanyId,
    value,
    contracts,
    onChange,
  }: {
    clientId: string;
    masterCompanyId?: string;
    value: string[];
    contracts: Record<string, ClientServiceContractDraft>;
    onChange: (value: string[], contracts: Record<string, ClientServiceContractDraft>) => void;
  }) {
    const client = data.clients.find((item) => item.id === clientId);
    const serviceOptions = servicesForMasterCompany(client?.masterCompanyId || masterCompanyId || defaultMasterCompanyId());
    function selectedContract(serviceId: string) {
      return { ...serviceContractDraft(clientId, serviceId), ...(contracts[serviceId] || {}) };
    }

    function toggleService(serviceId: string, checked: boolean) {
      if (checked) {
        onChange([...value, serviceId], { ...contracts, [serviceId]: selectedContract(serviceId) });
        return;
      }
      const nextContracts = { ...contracts };
      delete nextContracts[serviceId];
      onChange(value.filter((item) => item !== serviceId), nextContracts);
    }

    function updateContract(serviceId: string, patch: Partial<ClientServiceContractDraft>) {
      onChange(value, { ...contracts, [serviceId]: { ...selectedContract(serviceId), ...patch } });
    }

    return (
      <section className="client-services-field">
        <div>
          <span>Serviços cadastrados para este cliente</span>
          <small>Marque os serviços e ajuste o valor contratado quando houver negociação específica.</small>
        </div>
        {serviceOptions.length === 0 && <p className="form-hint">Nenhum serviço cadastrado ainda para esta empresa master. Cadastre os serviços no módulo Serviços para aparecerem aqui.</p>}
        {serviceOptions.length > 0 && (
          <div className="client-service-options">
            {serviceOptions.map((service) => {
              const checked = value.includes(service.id);
              const contract = selectedContract(service.id);
              return (
                <article key={service.id} className={`client-service-option ${checked ? 'selected' : ''}`}>
                  <label className="service-option-check">
                    <input
                      type="checkbox"
                      checked={checked}
                      onChange={(event) => toggleService(service.id, event.target.checked)}
                    />
                    <span>
                      <b>{service.name}</b>
                      <small>{service.category || 'Sem categoria'} · base {money(service.baseValue)}</small>
                    </span>
                  </label>
                  {checked && (
                    <div className="client-contract-grid">
                      <label>
                        Valor base
                        <input
                          type="number"
                          step="0.01"
                          value={service.baseValue}
                          disabled
                        />
                      </label>
                      <label>
                        Periodicidade
                        <select
                          value={contract.periodicity}
                          onChange={(event) => updateContract(service.id, { periodicity: event.target.value as ServicePeriodicity })}
                        >
                          {Object.entries(periodicityInfo).map(([periodicity, label]) => (
                            <option key={periodicity} value={periodicity}>{label}</option>
                          ))}
                        </select>
                      </label>
                      <label>
                        Dia de vencimento
                        <input
                          type="number"
                          min="1"
                          max="31"
                          value={contract.dueDay}
                          onChange={(event) => updateContract(service.id, { dueDay: Number(event.target.value) })}
                        />
                      </label>
                      <label>
                        Status
                        <select
                          value={contract.status}
                          onChange={(event) => updateContract(service.id, { status: event.target.value as ClientServiceStatus })}
                        >
                          {Object.entries(clientServiceStatusInfo).map(([status, info]) => (
                            <option key={status} value={status}>{info.label}</option>
                          ))}
                        </select>
                      </label>
                      <label>
                        Início do serviço
                        <input
                          type="date"
                          value={contract.startDate}
                          onChange={(event) => updateContract(service.id, { startDate: event.target.value })}
                        />
                      </label>
                      <label>
                        Fim do serviço
                        <input
                          type="date"
                          value={contract.endDate}
                          onChange={(event) => updateContract(service.id, { endDate: event.target.value })}
                        />
                      </label>
                      <label>
                        Quantidade
                        <input
                          type="number"
                          min="1"
                          step="1"
                          value={serviceQuantity(contract.quantity)}
                          onChange={(event) => updateContract(service.id, { quantity: serviceQuantity(Number(event.target.value)) })}
                        />
                      </label>
                      <label>
                        Valor unitário negociado
                        <input
                          type="number"
                          step="0.01"
                          value={contract.specificValue}
                          onChange={(event) => updateContract(service.id, { specificValue: Number(event.target.value) })}
                        />
                      </label>
                      <label>
                        Total contratado
                        <input value={money(contractTotalValue(contract))} disabled />
                      </label>
                    </div>
                  )}
                </article>
              );
            })}
          </div>
        )}
      </section>
    );
  }

