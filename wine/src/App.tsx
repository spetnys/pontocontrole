function whatsappConversationLabel(message?: WhatsappMessageLog, resolveLabel?: (phone: string) => string) {
  const phone = whatsappPhone(message?.phone || '');
  const resolved = resolveLabel?.(phone);
  if (resolved) return resolved;
  const isProviderOutbound = message?.direction === 'outbound' && !['manual', 'lote'].includes(String(message?.source || '').toLowerCase());
  const targetLabel = message?.targetLabel || '';
  const genericLabels = ['envio manual', 'lote', 'manual'];
  if (!isProviderOutbound && targetLabel && !genericLabels.includes(targetLabel.toLowerCase()) && whatsappPhone(targetLabel) !== phone) return targetLabel;
  return whatsappDisplayPhone(phone);
}

function whatsappConversations(messages: WhatsappMessageLog[], resolveLabel?: (phone: string) => string) {
  const grouped = new Map<string, WhatsappConversation>();
  messages.forEach((message) => {
    const phone = whatsappPhone(message.phone);
    if (!phone) return;
    const current = grouped.get(phone);
    const label = whatsappConversationLabel(message, resolveLabel);
    const nextTime = Date.parse(message.createdAt || '') || 0;
    const currentTime = Date.parse(current?.lastAt || '') || 0;
    if (!current) {
      grouped.set(phone, {
        phone,
        label,
        lastText: message.text || '',
        lastAt: message.createdAt,
        status: message.status,
        count: 1,
      });
      return;
    }
    current.count += 1;
    if (label && current.label === whatsappDisplayPhone(phone)) current.label = label;
    if (nextTime >= currentTime) {
      current.lastText = message.text || '';
      current.lastAt = message.createdAt;
      current.status = message.status;
    }
  });
  return Array.from(grouped.values()).sort((a, b) => (Date.parse(b.lastAt || '') || 0) - (Date.parse(a.lastAt || '') || 0));
}

